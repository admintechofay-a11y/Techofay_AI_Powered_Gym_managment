export type AppModule = (typeof APP_MODULES)[keyof typeof APP_MODULES];

export const ALL_MODULES: AppModule[] = Object.values(APP_MODULES);

export const PERMISSION_ACTIONS = {
  VIEW: 'view',
  CREATE: 'create',
  EDIT: 'edit',
  DELETE: 'delete',
  EXPORT: 'export',
} as const;

export type PermissionAction = (typeof PERMISSION_ACTIONS)[keyof typeof PERMISSION_ACTIONS];

export const ALL_ACTIONS: PermissionAction[] = Object.values(PERMISSION_ACTIONS);

export type PermissionString = `${AppModule}:${PermissionAction}`;

/**
 * Helper to build permission string: module:action
 */
export function buildPermission(module: AppModule, action: PermissionAction): PermissionString {
  return `${module}:${action}` as PermissionString;
}

